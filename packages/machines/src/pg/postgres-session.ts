/**
 * This document is the hold of a PostgreSQL 17.11 backend on one client connection, over its TCP
 * socket on Linux. The backend turns on SO_KEEPALIVE for each TCP socket. At the defaults of its
 * four TCP GUCs, it changes no keepalive option and no user timeout. Thus the namespace sysctls
 * give the idle time, the interval and the count. A GUC above 0 sets its socket option.
 *
 * Each timer of a backend is a SIGALRM timeout. At startup, the handler ends the process at once.
 * After the startup packet, each handler sets a flag and the latch, directly or by a signal. The
 * backend then acts at its next CHECK_FOR_INTERRUPTS. An idle timer and the transaction timer end
 * the session with FATAL. The statement timer and the lock timer end the statement with ERROR.
 *
 * A send to a slow or a lost client waits for the socket with no timeout. In that wait the
 * backend acts on SIGTERM and on the death of the postmaster only. A timer that fires there takes
 * effect after the send. Thus PostgreSQL gives no bound to a send: the kernel ends it, or SIGTERM
 * does.
 *
 * A timeout knob at 0 has no timer: give it as no bound (`infinite`). This is true of
 * `statement_timeout`, `lock_timeout`, `transaction_timeout`, `idle_in_transaction_session_timeout`,
 * `idle_session_timeout` and `client_connection_check_interval`.
 */
