/**
 * This document is HikariCP 7.1.0 over pgjdbc 42.7.13, for one connection of a pool. It gives the
 * states of the connection, from its creation to its close, and the timers that act on it. The
 * pool makes its connections one at a time, on one thread. At the defaults the pool has a fixed
 * size of 10, thus its idle timer has no effect.
 *
 * HikariCP reads no idle socket. It finds a dead connection only by a check. A borrow checks a
 * connection that was idle for more than 500 ms. The keepalive checks an idle connection each 96 to
 * 120 s from its creation. Each check is `isValid`: pgjdbc sends one Query message with an empty
 * string, with a read timeout of `validationTimeout`. A read timeout or an I/O error closes the
 * socket.
 *
 * pgjdbc sends nothing on an idle connection. Its only read timeout is `socketTimeout`, which is
 * off at the defaults, thus no timer of pgjdbc bounds a statement or the startup. Its connect
 * timeout of 10 s bounds only the TCP connect and the SSLRequest. At sslmode `prefer` (the
 * default), a read timeout in the connect starts one more connect with SSL off, in what remains of
 * the 10 s.
 *
 * HikariCP closes a connection at once when a statement fails with an SQLState of the class 08. It
 * also closes it for 57P01, 57P02, 57P03 and 0A000. pgjdbc gives 08006 for each I/O error of a
 * statement. Thus a reset, an end of the stream or a give-up of the kernel each close the
 * connection. HikariCP does not send a statement again.
 */
