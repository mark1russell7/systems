/**
 * This document is PgBouncer 1.26.1 in transaction pooling, for one server connection of a pool:
 * from its launch to its close. It also gives the wait of the pool before its next connection after
 * a failed login.
 *
 * PgBouncer reads the socket of each idle server, thus the end of the stream or a reset of an idle
 * server closes it at once. A black hole stops nothing that PgBouncer reads. Only a check of the
 * server, a timer of the kernel, server_idle_timeout or server_lifetime removes such a server. The
 * check is the empty query before a reuse, when the server was idle for longer than
 * server_check_delay (30 s). It acts at the defaults, and no timer bounds its reply. Thus behind a
 * black hole, the client that waits for the check stays in the queue until its query_wait_timeout.
 *
 * The TCP connect has a timer of libevent of server_connect_timeout, in whole seconds. The janitor
 * also bounds the whole login by server_connect_timeout, from the launch. After a failed login the
 * pool starts no connection for server_login_retry from the launch of the failed one. In that time
 * each client that needs a server fails at once, and a waiting client stays in the queue.
 */
